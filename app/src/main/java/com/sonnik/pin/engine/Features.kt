package com.sonnik.pin.engine

/**
 * Части приложения, которые можно выключить в Настройках → «Функции».
 * Выключение только прячет интерфейс: данные остаются, включили обратно — всё на месте.
 */
enum class Feature(val title: String, val description: String) {
    QUICK_ADD("Быстрое добавление", "Строка «Быстро: …» вверху «Сегодня»"),
    VOICE("Голосовой ввод", "Микрофон в строке быстрого добавления"),
    REVIEW("Разбор перенесённых", "Карточка «Разобрать перенесённые» на «Сегодня»"),
    UPCOMING("Скоро", "Задачи на ближайшие дни внизу «Сегодня»"),
    SWIPE_DONE("Свайп вправо", "Провести задачу вправо — выполнено (или вернуть); отмечать можно и квадратиком"),
    SWIPE_TOMORROW("Свайп влево", "Провести задачу влево — перенести на завтра"),
    CALENDAR_FIT(
        "Календарь без прокрутки",
        "Панель дня встаёт ровно под подсказками календаря, сам календарь не листается вверх-вниз; выключите — как раньше",
    ),
    HABITS("Привычки", "На «Сегодня», в «Итогах» и календаре; напоминания привычек"),
    LISTS("Списки", "Списки-проекты: выбор в задаче, фильтры, цветные метки"),
    MATRIX("Матрица", "Значок матрицы Эйзенхауэра на «Сегодня»"),
    FOCUS("Фокус-таймер", "Помодоро: кнопка в задаче, карточка в «Итогах»"),
    PEOPLE("Люди и подарки", "Вкладка «Люди»"),
    PLANS("Планы", "Вкладка «Планы»"),
    STATS("Итоги", "Вкладка со статистикой; если выключить, на её месте будет вкладка «Привычки»"),
    DRIVE_NETWORK(
        "Google Диск по сети",
        "Папка .md-файлов на Диске через вход в аккаунт Google и интернет; выключите — она пропадёт из настроек и не будет синхронизироваться. «Google Диск — файлом» (Pin.zip) работает как прежде",
    ),
    ;

    companion object {
        /** Выключенные хранятся строкой имён через запятую; неизвестные имена пропускаются. */
        fun parseDisabled(value: String?): Set<Feature> =
            value.orEmpty().split(',').mapNotNull { n -> entries.firstOrNull { it.name == n.trim() } }.toSet()

        fun formatDisabled(disabled: Set<Feature>): String = disabled.sortedBy { it.ordinal }.joinToString(",") { it.name }
    }
}
